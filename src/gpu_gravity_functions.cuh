**/
__global__ void self_grav_pp_kernel_tiled(
    const int *__restrict__ self_cell_flags_d,
    const int *__restrict__ self_use_full_d,
    const float4 *__restrict__ send_pos_mass,
    const float *__restrict__ send_h,
    gravity_gpu_values_recv *__restrict__ recv,
    const int *__restrict__ counts_d,
    const int *__restrict__ offsets_d,
    const int *__restrict__ active_counts_d,
    const int *__restrict__ active_offsets_d,
    const int *__restrict__ active_index_d,
    float r_s_inv,
    int ncells) {

  const int cell = blockIdx.x;
  if (cell >= ncells) return;

  const int counts = counts_d[cell];
  if (counts <= 0) return;

  const int flags = self_cell_flags_d[cell];
  const int ci_active = flags & 1;
  if (!ci_active) return;

  const int active_count = active_counts_d[cell];
  if (active_count <= 0) return;

  const int cell_offset = offsets_d[cell];

  const int use_full = self_use_full_d[cell];

  const int active_slot = blockIdx.y * blockDim.x + threadIdx.x;
  const int valid_target = active_slot < active_count;

  const int active_base = active_offsets_d[cell];

  const int local_pid =
      valid_target ? active_index_d[active_base + active_slot] : 0;

  float xi = 0.f;
  float yi = 0.f;
  float zi = 0.f;
  float hi = 0.f;

  if (valid_target) {
    const float4 pi = send_pos_mass[cell_offset + local_pid];

    xi = pi.x;
    yi = pi.y;
    zi = pi.z;
    hi = send_h[cell_offset + local_pid];
  }

  float ax = 0.f;
  float ay = 0.f;
  float az = 0.f;
  float pot = 0.f;

  extern __shared__ char smem[];

  float4 *sh_pos_mass = (float4 *)smem;
  float *sh_h = (float *)&sh_pos_mass[blockDim.x];

  for (int j0 = 0; j0 < counts; j0 += blockDim.x) {

    const int jload = j0 + threadIdx.x;

    if (jload < counts) {
      sh_pos_mass[threadIdx.x] = send_pos_mass[cell_offset + jload];
      sh_h[threadIdx.x] = send_h[cell_offset + jload];
    }

    __syncthreads();

    const int tile = min(blockDim.x, counts - j0);

    if (valid_target) {
      for (int j = 0; j < tile; j++) {

        const int src_local_pid = j0 + j;

        if (local_pid == src_local_pid) continue;

        const float4 pj = sh_pos_mass[j];

        const float xj = pj.x;
        const float yj = pj.y;
        const float zj = pj.z;
        const float mj = pj.w;
        const float hj = sh_h[j];

        const float dx = xj - xi;
        const float dy = yj - yi;
        const float dz = zj - zi;

        const float r2 = dx * dx + dy * dy + dz * dz;

        const float h = max(hi, hj);
        const float h2 = h * h;
        const float hinv = 1.f / h;
        const float hinv3 = hinv * hinv * hinv;

        float fij = 0.f;
        float potij = 0.f;

        if (use_full) {
          iact_grav_pp_full(r2, h2, hinv, hinv3, mj, &fij, &potij);
        } else {
          iact_grav_pp_truncated(
              r2, h2, hinv, hinv3, mj, r_s_inv, &fij, &potij);
        }

        ax += fij * dx;
        ay += fij * dy;
        az += fij * dz;
        pot += potij;
      }
    }

    __syncthreads();
  }

  if (valid_target) {
    const int out = active_base + active_slot;

    recv[out].values_i.x = ax;
    recv[out].values_i.y = ay;
    recv[out].values_i.z = az;
    recv[out].values_i.w = pot;
  }
}


/**
 * @brief Compute tiled direct pair-cell P-P gravity interactions for one side of each packed pair.
 *
 * This kernel is the shared-memory tiled variant of @ref pair_grav_pp_kernel,
 * loading source-particle data in tiles to reduce global memory traffic.
 *
 * @param send Device input buffer for packed particle pairs.
 * @param recv Device output buffer for accelerations and potential.
 * @param periodic Whether periodic boundary conditions are enabled.
 * @param r_s_inv Inverse splitting scale for truncated periodic forces.
 * @param symmetric Whether both sides of the pair are updated.
 * @param swap Selects which side of the packed pair is updated.
 * @param dim_0 Domain size in the x dimension.
 * @param dim_1 Domain size in the y dimension.
 * @param dim_2 Domain size in the z dimension.
 * @param max_cell_size Maximum number of particles per packed cell.
 * @param ncells Number of packed cell slots in the batch.
 */
__global__ void pair_grav_pp_kernel_tiled(
    const int *__restrict__ pair_cell_flags_d,
    const int *__restrict__ pair_use_full_d,
    const int *__restrict__ pair_side_active_offsets_d,
    const float4 *__restrict__ send_pos_mass,
    const float *__restrict__ send_h,
    gravity_gpu_values_recv *__restrict__ recv,
    const int *__restrict__ pair_counts_d,
    const int *__restrict__ pair_offsets_d,
    const int *__restrict__ pair_active_counts_d,
    const int *__restrict__ pair_active_offsets_d,
    const int *__restrict__ pair_active_index_d,
    const int *__restrict__ pair_pair_i_d,
    const int *__restrict__ pair_pair_j_d,
    int npairs,
    int nslots,
    int periodic,
    float r_s_inv,
    int swap,
    float dim_0,
    float dim_1,
    float dim_2,
    int ncells) {

  const int pair_id = blockIdx.x;
  if (pair_id >= npairs) return;

  const int slot0 = pair_pair_i_d[pair_id];
  const int slot1 = pair_pair_j_d[pair_id];

  if (slot0 < 0 || slot0 >= nslots) return;
  if (slot1 < 0 || slot1 >= nslots) return;

  const int target_slot = swap ? slot1 : slot0;
  const int source_slot = swap ? slot0 : slot1;

  const int base_i = pair_offsets_d[target_slot];
  const int base_j = pair_offsets_d[source_slot];

  const int count_j = pair_counts_d[source_slot];

  const int flags = pair_cell_flags_d[target_slot];
  const int ci_active = flags & 1;
  if (!ci_active) return;

  const int active_count_i = pair_active_counts_d[target_slot];
  if (active_count_i <= 0) return;

  const int active_slot = blockIdx.y * blockDim.x + threadIdx.x;
  const int valid_pid = active_slot < active_count_i;

  const int active_base = pair_active_offsets_d[target_slot];

  const int local_pid_i =
      valid_pid ? pair_active_index_d[active_base + active_slot] : 0;

  float xi = 0.f;
  float yi = 0.f;
  float zi = 0.f;
  float hi = 0.f;

  if (valid_pid) {
    const float4 pi = send_pos_mass[base_i + local_pid_i];

    xi = pi.x;
    yi = pi.y;
    zi = pi.z;
    hi = send_h[base_i + local_pid_i];
  }

  float ax = 0.f;
  float ay = 0.f;
  float az = 0.f;
  float pot = 0.f;

  const int use_full = pair_use_full_d[pair_id];

  extern __shared__ char smem[];

  float4 *sh_pos_mass = (float4 *)smem;
  float *sh_h = (float *)&sh_pos_mass[blockDim.x];

  for (int j0 = 0; j0 < count_j; j0 += blockDim.x) {

    const int jload = j0 + threadIdx.x;

    if (jload < count_j) {
      sh_pos_mass[threadIdx.x] = send_pos_mass[base_j + jload];
      sh_h[threadIdx.x] = send_h[base_j + jload];
    }

    __syncthreads();

    const int tile = min(blockDim.x, count_j - j0);

    if (valid_pid) {
      for (int j = 0; j < tile; j++) {

        const float4 pj = sh_pos_mass[j];

        const float xj = pj.x;
        const float yj = pj.y;
        const float zj = pj.z;
        const float mj = pj.w;
        const float hj = sh_h[j];

        float dx = xj - xi;
        float dy = yj - yi;
        float dz = zj - zi;

        if (periodic) {
          dx = nearestf1(dx, dim_0);
          dy = nearestf1(dy, dim_1);
          dz = nearestf1(dz, dim_2);
        }

        const float r2 = dx * dx + dy * dy + dz * dz;

        const float h = max(hi, hj);
        const float h2 = h * h;
        const float hinv = 1.f / h;
        const float hinv3 = hinv * hinv * hinv;

        float fij = 0.f;
        float potij = 0.f;

        if (use_full) {
          iact_grav_pp_full(r2, h2, hinv, hinv3, mj, &fij, &potij);
        } else {
          iact_grav_pp_truncated(
              r2, h2, hinv, hinv3, mj, r_s_inv, &fij, &potij);
        }

        ax += fij * dx;
        ay += fij * dy;
        az += fij * dz;
        pot += potij;
      }
    }

    __syncthreads();
  }

  if (valid_pid) {
    const int side = 2 * pair_id + swap;
    const int out_base = pair_side_active_offsets_d[side];
    const int out = out_base + active_slot;

    recv[out].values_i.x = ax;
    recv[out].values_i.y = ay;
    recv[out].values_i.z = az;
    recv[out].values_i.w = pot;
  }
}
